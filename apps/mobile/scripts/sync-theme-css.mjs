#!/usr/bin/env node
// Regenerates the :root token blocks in src/styles/global.css from the single
// source in src/lib/design-tokens.ts. Run after editing the palette; the
// check:nativewind-theme-vars guard fails on any drift.
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import {
  paletteKeyToCssVariable,
  readPalette,
  renderRootBlock,
} from "./lib/design-tokens-source.mjs"

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const cssPath = join(root, "src/styles/global.css")
const css = readFileSync(cssPath, "utf8")
const palette = readPalette(root)
const BEGIN = "/* design-tokens:begin (generated by scripts/sync-theme-css.mjs) */"
const END = "/* design-tokens:end */"

const generatedStart = css.includes(BEGIN)
  ? css.indexOf(BEGIN)
  : css.indexOf("@theme inline")
if (generatedStart < 0) throw new Error("global.css must keep its @theme inline block.")
const head = css.slice(0, generatedStart)
const colorKeys = [...palette.light.keys()].filter(
  (key) => key !== "radius" && !key.startsWith("chart")
)
const themeInline = `@theme inline {
${colorKeys
  .map((key) => {
    const name = paletteKeyToCssVariable(key)
    return `  --color-${name}: var(--${name});`
  })
  .join("\n")}
}
`
const generated = `${BEGIN}
${themeInline}
@layer base {
  :root {
${renderRootBlock(palette.light, "    ")}
  }
}

@media (prefers-color-scheme: dark) {
  @layer base {
    :root {
${renderRootBlock(
  new Map([...palette.dark].filter(([key]) => key !== "radius")),
  "      "
)}
    }
  }
}
${END}
`
writeFileSync(cssPath, `${head}${generated}`)
console.log(`global.css tokens synced (${palette.light.size} light, ${palette.dark.size - 1} dark).`)
